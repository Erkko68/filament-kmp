package buildlogic.apigen.kotlin

import buildlogic.apigen.KotlinBindings
import buildlogic.apigen.c.Abi
import buildlogic.apigen.c.CFunction
import buildlogic.apigen.c.CManifest
import java.io.File

/**
 * Writes the common `@ExternalSymbolName external fun` of a C header's functions, named like the C symbol (web binds
 * by global name), with the types externals take: any pointer is a `NativePointer`, 32-bit integers and enums an
 * `Int`, 64-bit ones a `Long`.
 */
internal object KotlinExternalsWriter {
    /** The Kotlin file binding [functions] (of the header `c/[source]`) in [pkg]; [interop]: the package declaring the two names. */
    fun write(source: String, functions: List<CFunction>, pkg: String, interop: String) =
        "// Generated by generateKotlinExternals from c/$source; do not edit.\n" +
            "package $pkg\n\nimport $interop.ExternalSymbolName\n" +
            (if (functions.any { f -> f.returns == Abi.POINTER || f.params.any { it.second == Abi.POINTER } }) "import $interop.NativePointer\n" else "") +
            functions.joinToString("") { "\n${external(it)}" }

    private fun external(f: CFunction): String {
        val params = f.params.joinToString { (name, abi) -> "${if (name in KEYWORDS) "`$name`" else name}: ${type(abi)}" }
        val result = if (f.returns == Abi.VOID) "" else ": ${type(f.returns)}"
        return "@ExternalSymbolName(\"${f.name}\")\ninternal external fun ${f.name}($params)$result\n"
    }

    private fun type(abi: Abi) = when (abi) {
        Abi.VOID -> "Unit"
        Abi.POINTER -> "NativePointer"
        Abi.I32 -> "Int"
        Abi.I64 -> "Long"
        Abi.F32 -> "Float"
        Abi.F64 -> "Double"
        Abi.BOOL -> "Boolean"
    }

    private val KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
        "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
        "when", "while",
    )
}

/** Each header's externals by path under the Kotlin dir. */
internal fun kotlinExternals(manifest: CManifest, bindings: KotlinBindings): Map<String, String> =
    manifest.headers.entries.associate { (header, functions) ->
        val module = header.substringBefore('/')
        val pkg = bindings.packages.getValue(module)
        "${packageDir(module, pkg)}/${File(header).nameWithoutExtension}.kt" to KotlinExternalsWriter.write(header, functions, pkg, bindings.interop)
    }

/** Where [module]'s externals in [pkg] live, under the Kotlin dir. */
internal fun packageDir(module: String, pkg: String) = "$module/src/commonMain/kotlin/${pkg.replace('.', '/')}"
