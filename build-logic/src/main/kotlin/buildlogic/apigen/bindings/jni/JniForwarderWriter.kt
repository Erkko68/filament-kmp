package buildlogic.apigen.bindings.jni

import buildlogic.apigen.c.Abi
import buildlogic.apigen.c.CFunction

/**
 * Writes the C side of the JNI bindings: for each external, the `Java_<class>_<name>` function the JVM
 * links it to, forwarding to the C function. Pointers cross as `jlong` and go through `void*`, which C converts
 * to the declared pointer type; the included C API prototypes let the C compiler check everything else.
 */
object JniForwarderWriter {
    /** The forwarders of [functions], the externals of [file] and so static methods of [jvmClass]. */
    fun write(file: String, jvmClass: String, functions: List<CFunction>, headers: Collection<String>): String = buildString {
        append("// Generated by GenerateBindings from $file. Do not edit.\n")
        append("#include <jni.h>\n#include <stdint.h>\n\n")
        headers.forEach { append("#include \"$it\"\n") }
        append("\n")
        val jniClass = mangle(jvmClass)
        functions.forEach { append(forwarder(jniClass, it)) }
    }

    private fun forwarder(jniClass: String, fn: CFunction): String {
        val params = fn.params.joinToString("") { (name, abi) -> ", ${type(abi)} $name" }
        val args = fn.params.joinToString { (name, abi) -> if (abi == Abi.POINTER) "(void*)(intptr_t) $name" else name }
        val call = "${fn.name}($args)"
        val body = when (fn.returns) {
            Abi.VOID -> "$call;"
            Abi.POINTER -> "return (jlong)(intptr_t) $call;"
            Abi.BOOL -> "return $call ? JNI_TRUE : JNI_FALSE;"
            else -> "return (${type(fn.returns)}) $call;"
        }
        return "JNIEXPORT ${type(fn.returns)} JNICALL Java_${jniClass}_${mangle(fn.name)}(JNIEnv* env, jclass cls$params) {\n    $body\n}\n\n"
    }

    private fun type(abi: Abi) = when (abi) {
        Abi.VOID -> "void"
        Abi.POINTER, Abi.I64 -> "jlong"
        Abi.I32 -> "jint"
        Abi.F32 -> "jfloat"
        Abi.F64 -> "jdouble"
        Abi.BOOL -> "jboolean"
    }

    // JNI name mangling: '_' → "_1", '.' → '_' (identifiers here are ASCII).
    private fun mangle(name: String) = name.replace("_", "_1").replace('.', '_')
}
