package buildlogic.apigen.bindings.wasm

import buildlogic.apigen.c.CFunction

/**
 * Writes `WASM_ARITIES` (runtime → export → parameter count) into [pkg] for the web export parity test: a Kotlin
 * declaration whose arity differs from the compiled C function has drifted from the header.
 */
object WasmArityTableWriter {
    fun write(byRuntime: Map<String, List<CFunction>>, pkg: String): String = buildString {
        append("// Generated by GenerateBindings. Do not edit.\npackage $pkg\n\n")
        append("val WASM_ARITIES: Map<String, List<Pair<String, Int>>> = mapOf(\n")
        byRuntime.forEach { (runtime, functions) ->
            append("    \"$runtime\" to listOf(\n")
            functions.forEach { append("        \"_${it.name}\" to ${it.params.size},\n") }
            append("    ),\n")
        }
        append(")\n")
    }
}
